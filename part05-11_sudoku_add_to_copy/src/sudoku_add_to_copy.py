def copy_and_add(sudoku: list, row_no: int, column_no: int, number: int):
    
    new_list=[]
    for row in sudoku:
        new_row = []
        for item in row:
            new_row.append(item)
        new_list.append(new_row)
            
        
    new_list[row_no][column_no] = number
    return new_list

